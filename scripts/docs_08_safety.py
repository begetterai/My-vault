def tbl(head, rows, widths=None):
    w = widths or []
    def _th(i, h):
        st = ' style="width:%s"' % w[i] if i < len(w) else ''
        return '<th%s>%s</th>' % (st, h)
    th = "".join(_th(i, h) for i, h in enumerate(head))
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><tr>{th}</tr>{tr}</table>"

