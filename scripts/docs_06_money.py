def tbl(head, rows, w=None):
    w = w or [None] * len(head)
    h = ['<table><tr>']
    for i, c in enumerate(head):
        st = f' style="width:{w[i]}"' if w[i] else ''
        h.append('<th%s>%s</th>' % (st, c))
    h.append('</tr>')
    for r in rows:
        h.append('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>')
    h.append('</table>')
    return ''.join(h)


