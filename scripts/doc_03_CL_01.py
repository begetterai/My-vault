def body(who, blocks):
    h = [f"""<h2>Зачем этот чек-лист</h2>
<p>Открытие — единственный момент смены, когда можно поймать все проблемы разом:
не вышел человек, не работает холодильник, кончились заготовки, не сходится касса.
Пропущенный пункт превращается в потерянную выручку или в жалобу гостя уже через час.</p>
<p><b>Каждый закрывает своё рабочее место.</b> Этот лист — только для позиции
«{who}». Чужие пункты в нём не отмечаются: за то, чего человек не видел,
он не расписывается.</p>
<p><b>Обе точки работают одинаково.</b> Разница одна: цех есть только на ЗБ,
поэтому на ОВИР листы цеха не заводятся.</p>
<p><b>Правило:</b> точка не открывается, пока свои листы не сдали все позиции.
Пункт, который невозможно выполнить, отмечается «✗» с комментарием,
а не пропускается.</p>

<h2>Как заполнять</h2>
<ul>
<li>Заполняет <b>{who}</b> за 60 минут до открытия.</li>
<li>Отметка: <b>✓</b> — выполнено, <b>✗</b> — не выполнено (обязателен комментарий).</li>
<li>Где указано «фото» — снимок обязателен, без него пункт не засчитывается.</li>
<li>Любое «✗» — немедленно управляющему, не дожидаясь конца смены.</li>
</ul>

<table class="meta">
<tr><th>Точка</th><td>&nbsp;</td><th style="width:14%">Дата</th><td>&nbsp;</td></tr>
<tr><th>{who} (ФИО)</th><td>&nbsp;</td><th>Время начала</th><td>&nbsp;</td></tr>
</table>"""]
    n = 0
    for name, items in [PERSONAL] + blocks:
        h.append(f'<p style="font-size:13pt"><b>{name}</b></p>')
        h.append('<table><tr><th class="num">№</th><th class="what">Что проверить</th>'
                 '<th class="norm">Норматив</th><th class="markw">Отм.</th>'
                 '<th class="mark">Фото</th><th class="cmt">Комментарий</th></tr>')
        for text, norm, photo in items:
            n += 1
            h.append(f'<tr><td class="num">{n}</td><td>{text}</td>'
                     f'<td class="small">{norm}</td><td class="markw">&nbsp;</td>'
                     f'<td class="mark">{photo}</td><td>&nbsp;</td></tr>')
        h.append('</table>')
    h.append(f"""<h2>Итог</h2>
<table class="meta">
<tr><th>Всего пунктов</th><td>{n}</td><th style="width:20%">Выполнено</th><td>&nbsp;</td></tr>
<tr><th>Не выполнено</th><td>&nbsp;</td><th>Сдано в</th><td>&nbsp;</td></tr>
</table>
<p class="sign"><b>{who}:</b> ____________________ &nbsp;&nbsp;
<b>Подпись:</b> ____________________</p>
<p class="sign"><b>Проверил управляющий:</b> ____________________ &nbsp;&nbsp;
<b>Дата и подпись:</b> ____________________</p>""")
    return "".join(h), n

