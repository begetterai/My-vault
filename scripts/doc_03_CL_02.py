def main():
    s = session()
    folder = folder_by_name(s, '03 Смена и обслуживание', ROOT)
    for suffix, zone_name, who, blocks in POSITIONS:
        code = f'03-CL-02/{suffix}'
        meta = dict(META, code=code, title=f'Закрытие смены — {zone_name}',
                    who=f'{who} — заполняет. Управляющий — проверяет.')
        b, n = body(who, blocks)
        html = build_html(meta, b, CONTROL, VIOLATION, sign_rows=8)
        name = f'{code} — Закрытие смены, {zone_name} (v1.0)'
        fid, act = put_doc(s, name, folder, html)
        n_style = enforce_font(s, fid)
        add_footer(s, fid, footer_text(meta))
        link = f'https://docs.google.com/document/d/{fid}'
        registry_update(s, REG, code, status='Черновик', version='v1.0',
                        date=meta['date'], review=meta['review'], link=link)
        print(f'{name} — {act}, пунктов: {n}, стилевых правок: {n_style}')
        print(link)

if __name__ == '__main__':
    main()
