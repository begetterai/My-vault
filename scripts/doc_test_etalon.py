#!/usr/bin/env python3
"""ТЕСТ — эталон оформления. Показывает ВСЕ элементы стандарта на одной странице,
чтобы утвердить вид один раз для всех 87 документов системы."""
import sys, datetime
sys.path.insert(0, '/home/user/My-vault/scripts')
from ops_docs import (session, build_html, put_doc, folder_by_name,
                      enforce_font, add_footer, footer_text)

ROOT = '1cSLEkOXikhTv0g6lPxZ31xJca1Yu-q43'
TODAY = datetime.date.today()

META = {
 'kind': 'ЭТАЛОН ОФОРМЛЕНИЯ', 'code': '00-FRM-00',
 'title': 'Тестовый документ — все элементы стандарта',
 'version': 'v1.0',
 'date': TODAY.strftime('%d.%m.%Y'),
 'owner': 'COO',
 'review': TODAY.replace(year=TODAY.year + 1).strftime('%d.%m.%Y'),
 'scope': 'Все документы системы',
 'who': 'Не для персонала. Служебный документ для утверждения вида.',
}

BODY = """
<h2>Назначение этого документа</h2>
<p>Здесь собраны <b>все элементы оформления</b>, которые встречаются в документах
операционной системы. Утверждаем вид один раз здесь — дальше все 87 документов
собираются автоматически по этому образцу.</p>
<p class="note">Содержание условное. Смотреть надо на оформление, а не на смысл.</p>

<h2>1. Заголовок второго уровня</h2>
<p>Обычный абзац. Используется для объяснений и правил. Внутри может быть
<b>жирный текст</b> для акцента на главном.</p>

<p style="font-size:13pt"><b>1.1. Заголовок блока внутри раздела</b></p>
<p>Так выделяются блоки внутри раздела — например, группы пунктов в чек-листе
или этапы в регламенте.</p>

<h2>2. Списки</h2>
<p>Маркированный — когда порядок не важен:</p>
<ul>
<li>первый пункт списка;</li>
<li>второй пункт списка;</li>
<li>третий пункт списка.</li>
</ul>
<p>Нумерованный — когда важна последовательность:</p>
<ol>
<li>сначала это;</li>
<li>потом это;</li>
<li>и только потом это.</li>
</ol>

<h2>3. Таблица-справка (узкая, два столбца)</h2>
<p>Используется для мета-данных, итогов и коротких справок:</p>
<table class="meta">
<tr><th>Показатель</th><td>Значение</td></tr>
<tr><th>Норматив времени</th><td>60 минут</td></tr>
<tr><th>Ответственный</th><td>Старший смены на кухне</td></tr>
</table>

<h2>4. Таблица рабочая (широкая, с отметками)</h2>
<p>Основная таблица чек-листов и регламентов:</p>
<table>
<tr><th class="num">№</th><th class="what">Что проверить или сделать</th>
<th class="norm">Норматив</th><th class="markw">Отм.</th>
<th class="mark">Фото</th><th class="cmt">Комментарий</th></tr>
<tr><td class="num">1</td><td>Пример пункта с нормативом времени</td>
<td class="small">за 60 мин</td><td class="markw">&nbsp;</td>
<td class="mark">фото</td><td>&nbsp;</td></tr>
<tr><td class="num">2</td><td>Пример пункта подлиннее, чтобы было видно,
как текст переносится внутри ячейки и не ломает таблицу</td>
<td class="small">&nbsp;</td><td class="markw">&nbsp;</td>
<td class="mark">&nbsp;</td><td>&nbsp;</td></tr>
<tr><td class="num">3</td><td>Пример короткого пункта</td>
<td class="small">10:00</td><td class="markw">&nbsp;</td>
<td class="mark">фото</td><td>&nbsp;</td></tr>
</table>

<h2>5. Таблица ролей (для регламентов)</h2>
<table>
<tr><th style="width:26%">Роль</th><th>Что делает</th></tr>
<tr><td>Старший смены на кухне</td><td>Выполняет и заполняет</td></tr>
<tr><td>Управляющий</td><td>Проверяет и подписывает</td></tr>
</table>

<h2>6. Подписи в тексте</h2>
<p class="sign"><b>Старший смены на кухне:</b> ____________________ &nbsp;&nbsp;
<b>Подпись:</b> ____________________</p>
<p class="sign"><b>Проверил управляющий:</b> ____________________ &nbsp;&nbsp;
<b>Дата:</b> ____________________</p>
"""

CONTROL = {
 'Кто проверяет': 'Управляющий точки — ежедневно',
 'Как проверяет': 'Сверяет заполненное с фото, выборочно перепроверяет лично',
 'Дополнительный контроль': 'COO — при визите на точку и по камерам',
 'Где хранится': 'На точке 3 месяца, затем архив',
}

VIOLATION = [
 ("Пример грубого нарушения", "Грубое нарушение"),
 ("Пример обычного нарушения", "Нарушение"),
 ("Пример мелкого недочёта", "Замечание"),
]

def main():
    s = session()
    folder = folder_by_name(s, '00 Управление системой документов', ROOT)
    html = build_html(META, BODY, CONTROL, VIOLATION, sign_rows=5)
    name = '00-FRM-00 — ТЕСТ: эталон оформления'
    fid, act = put_doc(s, name, folder, html)
    n = enforce_font(s, fid)
    add_footer(s, fid, footer_text(META))
    print(f'{name} — {act}, восстановлено жирных фрагментов: {n}')
    print(f'https://docs.google.com/document/d/{fid}')
    return fid

if __name__ == '__main__':
    main()
