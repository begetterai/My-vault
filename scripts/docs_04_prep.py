def main():
    s = session()
    for d in DOCS:
        m = d['m']
        folder = folder_by_name(s, d['folder'], ROOT)
        if not folder:
            print('НЕТ ПАПКИ: ' + d['folder'])
            continue
        html = build_html(m, d['body'], d['ctrl'], d['viol'], sign_rows=5)
        name = f"{m['code']} — {m['title']} (v1.0)"
        fid, act = put_doc(s, name, folder, html)
        n = enforce_font(s, fid)
        add_footer(s, fid, footer_text(m))
        link = f'https://docs.google.com/document/d/{fid}'
        registry_update(s, REG, m['code'], status='Черновик', version='v1.0',
                        date=m['date'], review=m['review'], link=link)
        print(f'{name:62s} {act:9s} жирных: {n}')
        print('   ' + link)


if __name__ == '__main__':
    main()
