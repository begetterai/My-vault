def tbl(head, rows, w=None):
    w = w or [None] * len(head)
    h = ['<table><tr>']
    for i, c in enumerate(head):
        st = f' style="width:{w[i]}"' if w[i] else ''
        h.append('<th%s>%s</th>' % (st, c))
    h.append('</tr>')
    for r in rows:
        h.append('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>')
    h.append('</table>')
    return ''.join(h)


def numbered(rows, head=('Что проверить или сделать', 'Норматив')):
    out = ['<table><tr><th class="num">№</th><th class="what">%s</th>'
           '<th class="norm">%s</th><th class="markw">Отм.</th>'
           '<th class="cmt">Комментарий</th></tr>' % head]
    for i, (t, n) in enumerate(rows, 1):
        out.append(f'<tr><td class="num">{i}</td><td>{t}</td>'
                   f'<td class="small">{n}</td><td class="markw">&nbsp;</td>'
                   f'<td>&nbsp;</td></tr>')
    out.append('</table>')
    return ''.join(out)


