def tbl(head, rows, w=None):
    w = w or [None] * len(head)
    h = ['<table><tr>']
    for i, c in enumerate(head):
        st = ' style="width:%s"' % w[i] if i < len(w) and w[i] else ''
        h.append('<th%s>%s</th>' % (st, c))
    h.append('</tr>')
    for r in rows:
        h.append('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>')
    h.append('</table>')
    return ''.join(h)


def checklist(blocks):
    """blocks: [(название, [(пункт, норматив, фото)])] → нумерация сквозная."""
    out, n = [], 0
    for name, items in blocks:
        out.append('<p style="font-size:13pt"><b>%s</b></p>' % name)
        out.append('<table><tr><th class="num">№</th><th class="what">Что сделать</th>'
                   '<th class="norm">Норматив</th><th class="markw">Отм.</th>'
                   '<th class="mark">Фото</th><th class="cmt">Комментарий</th></tr>')
        for t, nm, ph in items:
            n += 1
            out.append('<tr><td class="num">%d</td><td>%s</td>'
                       '<td class="small">%s</td><td class="markw">&nbsp;</td>'
                       '<td class="mark">%s</td><td>&nbsp;</td></tr>' % (n, t, nm, ph))
        out.append('</table>')
    return ''.join(out), n


