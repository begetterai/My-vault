#!/usr/bin/env python3
"""Форма Deep Clean — еженедельный субботник.

Источник: «Регламент Deep Clean (Субботник)» из папки «Ромашка регламенты
и чек листы». Раз в неделю всё заведение убирается всеми зонами сразу.

Решение Азиза 31.08.2026: **лист ведёт управляющий**. Он объявляет
субботник, обходит зоны и отмечает сам — по регламенту он и так
утверждающее лицо, а исполнители названы в самом пункте, чтобы было
видно, с кого спрашивать. Воскресенье, 10:00.

Критерий чистоты из регламента один на всё: провести белой сухой салфеткой
по поверхностям и углам — салфетка остаётся чистой.

Запуск: python3 scripts/build_deepclean.py
"""
import json

JSON = '/home/user/My-vault/ops-system/checklists.romashka.json'
KEY = 'deepclean'

# Зона → (кто убирает по регламенту, что именно доводят до глубокой чистоты)
ZONES = [
 ('Вход и фасад', 'уборщица',
  'входная группа, двери, порог, наружные поверхности окон'),
 ('Гостевой зал', 'кассиры',
  'все столы и стулья, пол, стены, декор, батареи'),
 ('Гостевая уборная', 'уборщица',
  'пол, стены, двери, раковина, зеркало, дозаторы, ёрш'),
 ('Кассовая зона', 'кассиры',
  'стойка, полки, стены, обшивка стойки, стены под кухонной выдачей, '
  'тепловые лампы, оборудование и кассовый инвентарь'),
 ('Бар', 'бариста',
  'оборудование, стены, полки, инвентарь, лайтбоксы'),
 ('Окно выдачи заказов', 'кухонный персонал',
  'внутренняя сторона и поверхность'),
 ('Стафф-зона', 'уборщицы',
  'стены, мойка, столы, оборудование не с кухни, мебель'),
 ('Цех', 'заготовщики',
  'оборудование, стены, столы и инвентарь'),
 ('Кухня', 'повара кухни',
  'стены, полки, столы, оборудование, вытяжка, инвентарь'),
]

# Восемь шагов регламента. Отмечаются один раз на весь субботник: это
# порядок работы, а не отдельная задача по каждой зоне.
STEPS = [
 ('Демонтаж выполнен: сняты фильтры, решётки, барматы, полки', '', False),
 ('Сухая уборка сделана: паутина, крупный мусор, сметание', '', False),
 ('Химия нанесена и выдержана по инструкции средства', '', False),
 ('Влажная очистка проведена сверху вниз', '', False),
 ('Всё протёрто насухо, разводов нет', '', False),
 ('Снятое собрано и установлено на место', '', False),
]

GENERAL = [
 ('Субботник объявлен смене заранее, зоны распределены', '', False),
 ('<b>Вытяжка:</b> Шуманит, выдержка 15–30 минут, металлическая щётка',
  '15–30 мин', False),
 ('<b>Пол под оборудованием:</b> холодильники, плиты и столы отодвинуты. '
  'Полностью — раз в месяц, еженедельно — где есть доступ', '', False),
 ('Работа с химией по правилам: перчатки надеты, средства не смешивались, '
  'помещение проветрено', '', False),
 ('Вода внутрь электроприборов не попадала', '', False),
]

FINAL = [
 ('<b>Контроль белой салфеткой пройден по всем зонам:</b> провести сухой '
  'белой салфеткой по поверхностям и углам — остаётся чистой', '', True),
 ('Фото «после» собраны по каждой зоне: 3–5 снимков — общий план плюс '
  'углы, места под оборудованием, вытяжка, полки', '3–5 на зону', True),
 ('Зоны, сданные формально, переделаны в тот же день', '', False),
 ('Замечания записаны в журнал смены, если переделка повторная', '', False),
]


def blocks():
    out = [{'name': 'Организация субботника',
            'items': [{'text': t, 'norm': n, 'photo': p} for t, n, p in GENERAL]},
           {'name': 'Порядок работы в каждой зоне',
            'items': [{'text': t, 'norm': n, 'photo': p} for t, n, p in STEPS]}]
    items = []
    for zone, who, what in ZONES:
        items.append({
            'text': f'<b>{zone}</b> — {what}. Доведено до глубокой чистоты, '
                    f'проверено лично. Убирает: {who}',
            'norm': '', 'photo': True})
    out.append({'name': 'Зоны — принимает управляющий', 'items': items})
    out.append({'name': 'Итог',
                'items': [{'text': t, 'norm': n, 'photo': p} for t, n, p in FINAL]})
    return out


def main():
    data = json.load(open(JSON, encoding='utf-8'))
    b = blocks()
    data[KEY] = {
        'title': 'Deep Clean — субботник',
        'code': '04-CL-02',
        'roles': ['manager', 'coo'],
        'ask_time': 'Во сколько закончили субботник?',
        'type': 'checklist',
        # Срок недельный, а не дневной: бот напоминает в воскресенье в 10:00
        # (schedule.deepclean_reminder), просрочка по дню не считается.
        'weekly': {'day': 6, 'at': '10:00'},
        'blocks': b,
    }
    json.dump(data, open(JSON, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    n = sum(len(x['items']) for x in b)
    print(f'{KEY}: {len(b)} блоков, {n} пунктов · форм в файле: {len(data)}')


if __name__ == '__main__':
    main()
