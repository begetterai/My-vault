def items(rows):
    return [{'text': t, 'norm': n, 'photo': p} for t, n, p in rows]


def blocks():
    out = [{'name': 'Организация субботника', 'items': items(GENERAL)},
           {'name': 'Порядок работы в каждой зоне', 'items': items(STEPS)}]
    for zone, who, rows in ZONES:
        out.append({'name': f'{zone} — убирает: {who}', 'items': items(rows)})
    out.append({'name': 'Итог — принимает управляющий', 'items': items(FINAL)})
    return out


def main():
    data = json.load(open(JSON, encoding='utf-8'))
    b = blocks()
    data[KEY] = {
        'title': 'Deep Clean — субботник',
        'code': '04-CL-02',
        'roles': ['manager', 'coo'],
        'ask_time': 'Во сколько закончили субботник?',
        'type': 'checklist',
        # Срок недельный, а не дневной: бот напоминает в воскресенье в 10:00
        # (schedule.deepclean_reminder), просрочка по дню не считается.
        'weekly': {'day': 6, 'at': '10:00'},
        'blocks': b,
    }
    json.dump(data, open(JSON, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    n = sum(len(x['items']) for x in b)
    print(f'{KEY}: {len(b)} блоков, {n} пунктов · форм в файле: {len(data)}')


if __name__ == '__main__':
    main()
