def flat(kind):
    """[(сквозной №, блок, текст)] по виду чек-листа."""
    out, n = [], 0
    for block, rows in KINDS[kind]['blocks']:
        for text, norm, photo in rows:
            n += 1
            out.append((n, block, text))
    return out


def by_block(kind):
    """[(блок, [(сквозной №, текст, норматив)])]"""
    out, n = [], 0
    for block, rows in KINDS[kind]['blocks']:
        cur = []
        for text, norm, photo in rows:
            n += 1
            cur.append((n, text, norm))
        out.append((block, cur))
    return out


def total(kind):
    return len(flat(kind))
