def equip_block(code, when):
    """Пункты по оборудованию зоны.

    Смысл из концепта v5 (01-DK-04): «включается, работает» — то есть
    проверка включением, а не осмотром. Чистота добавлена нами: исправный,
    но грязный зонт проверку проходить не должен. Форма безличная и без
    числа — «Фритюрницы 3 шт. — включается» звучало бы неграмотно.
    Своё требование прибавляется через точку с запятой.
    """
    items = []
    for x in EQUIP.get(code, []):
        name, _, req = x.partition('||')
        text = f'{name} — проверка включением пройдена, чистота в норме'
        if req:
            text += f'; {req}'
        items.append((text, '', ''))
    return (f'Оборудование зоны — проверка {when}', items)


def collect(src, code):
    """Достать блоки этапа для рабочего места из исходного скрипта."""
    for suffix, _zone, _who, blocks in src.POSITIONS:
        if suffix == code:
            return blocks
    return []


