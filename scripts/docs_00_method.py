def main():
    s = session()
    folder = folder_by_name(s, FOLDER, ROOT)
    if not folder:
        print('НЕТ ПАПКИ: ' + FOLDER)
        return
    for d in DOCS:
        m = d['m']
        html = build_html(m, d['body'], d['ctrl'], d['viol'], sign_rows=4)
        name = f"{m['code']} — {m['title']} (v1.0)"
        fid, act = put_doc(s, name, folder, html)
        enforce_font(s, fid)
        add_footer(s, fid, footer_text(m))
        link = f'https://docs.google.com/document/d/{fid}'
        registry_update(s, REG, m['code'], status='Черновик', version='v1.0',
                        date=D, review=REVIEW, link=link)
        print(f'{name:62s} {act}')
        print('   ' + link)

    # Групповые строки: это не документы, а наборы. «Не начат» вводит в
    # заблуждение — часть уже есть.
    for code, note in (
        ('04-TTK-*', 'Группа документов, не один файл. Часть техкарт есть '
                     'на корпоративном диске, техкарты шаурмы — в PNG. '
                     'Требуется ревизия и перенос в систему.'),
        ('09-INS-*', 'Группа документов. Общая инструкция 09-INS-01 написана; '
                     'отдельные инструкции заводятся по мере составления '
                     'реестра оборудования 09-REF-01.'),
    ):
        registry_update(s, REG, code, status='Черновик', date=D, review=REVIEW)
        print(f'{code:62s} помечен как группа')
        print('   ' + note)


if __name__ == '__main__':
    main()
