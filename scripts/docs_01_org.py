def dk(code, title, boss, subs, purpose, duties, results, decides, agrees,
       metrics, knows, forbidden):
    body = f"""
<h2>Зачем эта роль</h2>
<p>{purpose}</p>

<h2>Место в структуре</h2>
""" + tbl(['Подчиняется', 'Руководит', 'Заменяет на время отсутствия'],
              [[boss, subs, 'Назначается управляющим письменно']],
              ['30%', '38%', None]) + """
<h2>Что делает</h2>
"""
    for block, items in duties:
        body += f'<p style="font-size:13pt"><b>{block}</b></p><ul>'
        body += ''.join(f'<li>{x}</li>' for x in items) + '</ul>'
    body += """
<h2>За что отвечает лично</h2>
<ul>""" + ''.join(f'<li>{x}</li>' for x in results) + """</ul>

<h2>Что решает сам, что согласовывает</h2>
""" + tbl(['Решает сам', 'Согласовывает с руководителем'],
              [['<ul>' + ''.join(f'<li>{x}</li>' for x in decides) + '</ul>',
                '<ul>' + ''.join(f'<li>{x}</li>' for x in agrees) + '</ul>']],
              ['50%', None]) + """
<h2>По чему оценивается</h2>
<ul>""" + ''.join(f'<li>{x}</li>' for x in metrics) + """</ul>

<h2>Обязан знать и соблюдать</h2>
<p>""" + ' · '.join(knows) + """</p>
<p class="note">Ознакомление с этими документами подтверждается подписью
в листе ознакомления (<b>00-FRM-04</b>). Незнание документа не освобождает
от ответственности за его нарушение.</p>

<h2>Чего делать нельзя</h2>
<ul>""" + ''.join(f'<li>{x}</li>' for x in forbidden) + """</ul>

<p class="sign"><b>С должностной картой ознакомлен:</b> ____________________ &nbsp;&nbsp;
<b>Подпись:</b> ____________________ &nbsp;&nbsp; <b>Дата:</b> ____________</p>
"""
    return body


