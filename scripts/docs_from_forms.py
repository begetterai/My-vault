def main():
    s = session()
    forms = json.load(open(FORMS, encoding='utf-8'))
    # сквозная нумерация пунктов в файле не хранится — её проставляет
    # приложение при загрузке. Повторяем ту же логику, чтобы номера
    # в документе совпадали с номерами на экране.
    for cl in forms.values():
        n = 0
        for b in cl.get('blocks') or []:
            for it in b['items']:
                n += 1
                it['n'] = n
    made = 0
    for key, cl in forms.items():
        code = cl['code']
        if code not in PLACE:
            continue
        folder_name, owner, who = PLACE[code]
        folder = folder_by_name(s, folder_name, ROOT)
        if not folder:
            print('НЕТ ПАПКИ: ' + folder_name)
            continue
        t = cl.get('type', 'checklist')
        body = {'checklist': body_checklist, 'journal': body_fields,
                'form': body_blank, 'shift': body_shift}[t](cl)
        m = {'kind': KIND[t], 'code': code, 'title': cl['title'], 'version': VER,
             'date': D, 'owner': owner, 'review': REVIEW, 'scope': SCOPE, 'who': who}
        html = build_html(m, body, CTRL, VIOL.get(code, []), sign_rows=6)
        name = f"{code} — {cl['title']} (v1.0)"
        fid, act = put_doc(s, name, folder, html)
        enforce_font(s, fid)
        add_footer(s, fid, footer_text(m))
        link = f'https://docs.google.com/document/d/{fid}'
        registry_update(s, REG, code, status='Черновик', version='v1.0',
                        date=D, review=REVIEW, link=link)
        print(f'{name:56s} {act}')
        print('   ' + link)
        made += 1
    print(f'\nсобрано из форм приложения: {made}')


if __name__ == '__main__':
    main()
