def rows(cols, n):
    return "".join("<tr>" + "".join("<td>&nbsp;</td>" for _ in range(cols)) + "</tr>"
                   for _ in range(n))

def tbl(head, data, widths=None):
    w = widths or []
    def _th(i, h):
        st = ' style="width:%s"' % w[i] if i < len(w) and w[i] else ''
        return '<th%s>%s</th>' % (st, h)
    th = "".join(_th(i, h) for i, h in enumerate(head))
    tr = "".join("<tr>" + "".join("<td>%s</td>" % c for c in r) + "</tr>" for r in data)
    return "<table><tr>%s</tr>%s</table>" % (th, tr)

