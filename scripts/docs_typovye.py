def main():
    s = session()
    print("Типовые документы\n")
    for d in DOCS:
        m = d['m']
        folder = folder_by_name(s, d['folder'], ROOT)
        html = build_html(m, d['body'], d['control'], d['viol'], sign_rows=0)
        name = "%s — %s (%s)" % (m['code'], m['title'], m['version'])
        fid, act = put_doc(s, name, folder, html)
        enforce_font(s, fid)
        add_footer(s, fid, footer_text(m))
        link = "https://docs.google.com/document/d/%s" % fid
        registry_update(s, REG, m['code'], status='Черновик', version=m['version'],
                        date=D, review=R, link=link)
        print("  %-9s %-11s %s" % (act, m['code'], m['title'][:48]))
        print("            %s" % link)

if __name__ == '__main__':
    main()
