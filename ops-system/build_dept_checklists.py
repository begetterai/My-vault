def main():
    raw = open(PATH, encoding='utf-8').read()
    data = json.loads(raw, object_pairs_hook=collections.OrderedDict)

    # Общие чек-листы остаются управляющему: он проверяет точку целиком,
    # а не отдел. Линейным они больше не показываются.
    for k in ('open', 'close'):
        data[k]['roles'] = ['manager', 'coo']
        data[k]['dept'] = ''

    out = collections.OrderedDict()
    for k, v in data.items():
        out[k] = v
        if k == 'close':                      # новые ставим сразу после общих
            for nk, nv in NEW.items():
                out[nk] = nv
    for nk, nv in NEW.items():                # на случай, если 'close' не первый
        out.setdefault(nk, nv)

    open(PATH, 'w', encoding='utf-8').write(
        json.dumps(out, ensure_ascii=False, indent=2) + '\n')

    print('форм в файле:', len(out))
    for k, v in out.items():
        if v.get('type', 'checklist') == 'checklist':
            n = sum(len(b['items']) for b in v.get('blocks', []))
            print(f"  {v['code']:14s} {v['title']:24s} отдел: {v.get('dept','—'):8s}"
                  f" пунктов: {n:2d} роли: {','.join(v.get('roles', [])) or 'все'}")


if __name__ == '__main__':
    main()
