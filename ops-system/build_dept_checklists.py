def it(text, norm='', photo=False):
    return {'text': text, 'norm': norm, 'photo': photo}


def cl(title, code, dept, roles, deadline, ask, blocks, measures=None,
       points=None):
    out = {'title': title, 'code': code, 'type': 'checklist', 'dept': dept,
           'ask_time': ask, 'deadline': deadline,
           'measures': measures or {}, 'blocks': blocks}
    if roles:
        out['roles'] = roles
    if points:
        out['points'] = points
    return out


