def main():
    data = json.load(open(FILE, encoding='utf-8'),
                     object_pairs_hook=collections.OrderedDict)
    for key, cl in NEW.items():
        data[key] = cl
    json.dump(data, open(FILE, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    by = collections.Counter(cl.get('type', 'checklist') for cl in data.values())
    print(f'форм всего: {len(data)} · ' + ' · '.join(f'{k}: {v}' for k, v in by.items()))
    for key, cl in data.items():
        if key in NEW:
            t = cl['type']
            size = (f"{sum(len(b['items']) for b in cl['blocks'])} пунктов"
                    if t == 'checklist' else f"{len(cl['columns'])} колонок")
            print(f"  + {cl['code']:11} {cl['title']:32} {t:9} {size}")


if __name__ == '__main__':
    main()
