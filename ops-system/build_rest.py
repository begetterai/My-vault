UNITS = ['кг', 'г', 'л', 'мл', 'шт', 'упак']


def block(name, *items):
    out = []
    for it in items:
        if isinstance(it, str):
            it = (it, '', False)
        text, norm, photo = (list(it) + ['', False])[:3]
        out.append({'text': text, 'norm': norm, 'photo': bool(photo)})
    return {'name': name, 'items': out}


def f(key, label, kind='text', **kw):
    d = {'key': key, 'label': label, 'kind': kind}
    d.update(kw)
    return d


def find(blocks, needle):
    n = 0
    for b in blocks:
        for it in b['items']:
            n += 1
            if needle.lower() in it['text'].lower():
                return n
    raise KeyError(needle)


