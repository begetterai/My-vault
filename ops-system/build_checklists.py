import json, collections, pathlib

FILE = pathlib.Path(__file__).parent / 'checklists.romashka.json'


def block(name, *items):
    """items: строка «текст» либо кортеж (текст, норматив, фото)"""
    out = []
    for it in items:
        if isinstance(it, str):
            it = (it, '', False)
        text, norm, photo = (list(it) + ['', False])[:3]
        out.append({'text': text, 'norm': norm, 'photo': bool(photo)})
    return {'name': name, 'items': out}


def find(blocks, needle):
    """Сквозной номер пункта по куску текста — чтобы замеры не привязывать вручную."""
    n = 0
    for b in blocks:
        for it in b['items']:
            n += 1
            if needle.lower() in it['text'].lower():
                return n
    raise KeyError(needle)


